#!/usr/bin/env node
// Turns the color themes shipped in @mfp-design-system/tokens into
// src/lib/mfpThemes.ts, so the app can switch between them at run time.
//
// The design system ships each theme as a CSS file that redefines the same
// variables on `:root` — fine for a site that loads exactly one, but
// loading two would just make the last one win. This app lets each store
// pick its theme, so it needs every theme's values side by side as data.
// This script reads them straight out of the installed package (base
// tokens + each theme's overrides), follows `var(--x)` references through
// to real color values, and writes the result.
//
// Re-run after upgrading the tokens package: npm run sync-themes
const fs = require('fs');
const path = require('path');

const BUILD = path.join(__dirname, '..', 'node_modules', '@mfp-design-system', 'tokens', 'build');
const OUT = path.join(__dirname, '..', 'src', 'lib', 'mfpThemes.ts');

// The design-system variables this app actually uses (see src/lib/theme.ts).
const WANTED = [
  'color-brand-primary',
  'color-brand-primary-hover',
  'color-brand-primary-subtle',
  'color-brand-primary-emphasis',
  'color-text-default',
  'color-background-default',
  'color-background-subtle',
  'color-background-muted',
  'color-status-success-solid',
  'color-status-warning-solid',
  'color-status-info-solid',
  'color-status-error-solid',
];

// "Dark" is deliberately left out: it restyles every neutral (text, borders,
// backgrounds), and this app still hard-codes many of its greys, so it
// would come out half dark and unreadable.
const SKIP = new Set(['dark']);

function parseVars(css) {
  const vars = {};
  const withoutComments = css.replace(/\/\*[\s\S]*?\*\//g, '');
  for (const m of withoutComments.matchAll(/--([\w-]+)\s*:\s*([^;]+);/g)) vars[m[1]] = m[2].trim();
  return vars;
}

function resolve(name, vars, seen = new Set()) {
  if (seen.has(name)) throw new Error(`Circular reference at --${name}`);
  seen.add(name);
  const value = vars[name];
  if (value === undefined) throw new Error(`--${name} is not defined by the tokens package`);
  const ref = value.match(/^var\(--([\w-]+)\)$/);
  return ref ? resolve(ref[1], vars, seen) : value;
}

const base = parseVars(fs.readFileSync(path.join(BUILD, 'css', 'tokens.css'), 'utf8'));
const version = require(path.join(BUILD, '..', 'package.json')).version;
const themes = {};
for (const file of fs.readdirSync(path.join(BUILD, 'themes')).sort()) {
  const name = path.basename(file, '.css');
  if (SKIP.has(name)) continue;
  const vars = { ...base, ...parseVars(fs.readFileSync(path.join(BUILD, 'themes', file), 'utf8')) };
  themes[name] = Object.fromEntries(WANTED.map((key) => [key, resolve(key, vars)]));
}

const body = Object.entries(themes)
  .map(
    ([name, values]) =>
      `  ${name}: {\n${Object.entries(values)
        .map(([key, value]) => `    '${key}': '${value}',`)
        .join('\n')}\n  },`
  )
  .join('\n');

fs.writeFileSync(
  OUT,
  `// GENERATED by scripts/sync-mfp-themes.js from @mfp-design-system/tokens@${version}.\n` +
    `// Do not edit by hand — run \`npm run sync-themes\` instead.\n` +
    `export const MFP_THEMES = {\n${body}\n} as const;\n\n` +
    `export type MfpThemeName = keyof typeof MFP_THEMES;\n`
);
console.log(`[sync-mfp-themes] wrote ${Object.keys(themes).length} themes (${Object.keys(themes).join(', ')}) from tokens@${version}`);
